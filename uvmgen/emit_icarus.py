"""Emit a self-checking SystemVerilog testbench that Icarus Verilog can run.

Icarus has no virtual interfaces, constraints or mailboxes inside classes, so
this flavour keeps the UVM *architecture* (stimulus sequences -> driver ->
DUT -> monitor -> scoreboard with a reference model -> coverage) but builds it
from module-level tasks. The UVM flavour (emit_uvm.py) uses the same plan.

Per cycle:   negedge: sequence `pre`, drive inputs, maybe reset
             +1 ns : (reset -> model reset) model outputs -> compare -> coverage
             posedge: model step (unless in reset)
"""
from __future__ import annotations

from .plan import driven_inputs, outputs


def _w(width: int) -> str:
    return f"[{width - 1}:0] " if width > 1 else ""


def _indent(code: str, n: int) -> str:
    pad = " " * n
    return "\n".join(pad + l if l.strip() else "" for l in code.strip().splitlines())


def emit(plan: dict, ports: dict) -> str:
    clk, rst = plan["clock"], plan["reset"]["port"]
    act = plan["reset"]["active"]
    ins, outs = driven_inputs(plan, ports), outputs(ports)
    period = plan.get("period_ns", 10)
    defaults = plan.get("defaults", {})
    params = plan.get("params", {})

    L = ["`timescale 1ns/1ps", "// Generated by uvmgen from the verification plan. Do not edit.",
         "module tb;"]
    L.append(f"    logic {clk} = 1'b0;")
    L.append(f"    logic {rst} = 1'b{act};")
    for n in ins:
        L.append(f"    logic {_w(ports[n][1])}{n};")
    for n in outs:
        L.append(f"    logic {_w(ports[n][1])}{n};")
        L.append(f"    logic {_w(ports[n][1])}exp_{n};")
        L.append(f"    bit   chk_{n};")
    pstr = (" #(" + ", ".join(f".{k}({v})" for k, v in params.items()) + ")") if params else ""
    conns = ", ".join(f".{n}({n})" for n in ports)
    L.append(f"\n    {plan['dut']}{pstr} dut ({conns});")
    L.append(f"\n    always #{period / 2} {clk} = ~{clk};")

    L.append("\n    // ---------------- reference model ----------------")
    L.append(_indent(plan["model"]["decls"], 4))
    L.append("    function automatic void m_reset();\n" + _indent(plan["model"]["reset"], 8) + "\n    endfunction")
    sets = "\n".join(f"        chk_{n} = 1'b1;" for n in outs)
    L.append("    function automatic void m_outputs();\n" + sets + "\n" + _indent(plan["model"]["outputs"], 8)
             + "\n    endfunction")
    L.append("    function automatic void m_step();\n" + _indent(plan["model"]["step"], 8) + "\n    endfunction")

    L.append("\n    // ---------------- sequence variables ----------------")
    L.append("    int i;")
    if plan.get("seq_vars"):
        L.append(_indent(plan["seq_vars"], 4))

    cov = plan["coverage"]
    L.append("\n    // ---------------- scoreboard + coverage ----------------")
    L.append(f"    int cov_hits [{max(len(cov), 1)}];")
    L.append("    int errors = 0, checks = 0, cyc = 0;")
    L.append("    string cur_seq;")
    L.append("    task automatic check();")
    L.append("        m_outputs();")
    L.append("        checks++;")
    for n in outs:
        L.append(f"        if (chk_{n} && ({n} !== exp_{n})) begin")
        L.append("            errors++;")
        L.append("            if (errors <= 12)")
        ins_fmt = " ".join(f"{n2}=%0h" for n2 in ins)
        ins_args = ", ".join(ins)
        L.append(f'                $display("MISMATCH cycle=%0d seq=%s i=%0d port={n} got=%0h exp=%0h | {rst}=%0b {ins_fmt}",'
                 f" cyc, cur_seq, i, {n}, exp_{n}, {rst}{', ' + ins_args if ins else ''});")
        L.append("        end")
    for k, c in enumerate(cov):
        L.append(f"        if ({c['expr']}) cov_hits[{k}]++;")
    L.append("    endtask")

    L.append("\n    task automatic drive_defaults();")
    for n in ins:
        L.append(f"        {n} = {defaults.get(n, '0')};")
    L.append("    endtask")

    L.append("\n    initial begin")
    L.append("        drive_defaults();")
    L.append(f"        {rst} = 1'b{act};")
    L.append("        m_reset();")
    L.append(f"        repeat ({plan['reset'].get('cycles', 3)}) @(negedge {clk});")
    L.append(f"        {rst} = 1'b{1 - act};")
    for s in plan["sequences"]:
        L.append(f"\n        // sequence: {s['name']}")
        L.append(f'        cur_seq = "{s["name"]}";')
        L.append(f"        for (i = 0; i < {s['cycles']}; i++) begin")
        L.append(f"            @(negedge {clk});")
        L.append("            cyc++;")
        L.append("            drive_defaults();")
        if s.get("pre"):
            L.append(_indent(s["pre"], 12))
        for n, e in s.get("drive", {}).items():
            L.append(f"            {n} = {e};")
        rw = s.get("reset_when")
        L.append(f"            {rst} = ({rw}) ? 1'b{act} : 1'b{1 - act};" if rw else f"            {rst} = 1'b{1 - act};")
        L.append("            #1;")
        L.append(f"            if ({rst} == 1'b{act}) m_reset();")
        L.append("            check();")
        L.append(f"            @(posedge {clk});")
        L.append(f"            if ({rst} != 1'b{act}) m_step();")
        L.append("        end")
    L.append("")
    for k, c in enumerate(cov):
        L.append(f'        $display("COVER {c["name"]} %0d", cov_hits[{k}]);')
    L.append('        $display("CHECKS %0d ERRORS %0d", checks, errors);')
    L.append('        if (errors == 0) $display("PASS"); else $display("FAIL");')
    L.append("        $finish;")
    L.append("    end")
    L.append("endmodule")
    return "\n".join(L) + "\n"
